/**
 * CloudE5 — Platform administrator bootstrap.
 *
 * A fresh CloudE5 installation has no accounts. Customer organisations register themselves;
 * the platform operator's first administrator is created with this module (via
 * `npm run admin:create`). It is idempotent:
 *
 * - The platform operator tenant ("CloudE5 Platform", type TLI) is created once.
 * - An existing administrator with the same email is never modified unless `resetPassword` is set.
 * - A strong random password is generated unless the operator supplies one. It is returned once so
 *   the CLI can write it to a 0600 credentials file; it is never logged or stored in plaintext.
 */

import crypto from "node:crypto";
import { pool } from "../db/pool.ts";
import { hashPassword } from "../auth/passwords.ts";

export const PLATFORM_TENANT_SLUG = "cloude5-platform";
export const PLATFORM_TENANT_NAME = "CloudE5 Platform";
export const MIN_ADMIN_PASSWORD_LENGTH = 14;

const PASSWORD_CHARSETS = {
  lower: "abcdefghijkmnopqrstuvwxyz",
  upper: "ABCDEFGHJKLMNPQRSTUVWXYZ",
  digit: "23456789",
  symbol: "!@#$%^&*-_=+?",
};

/** Generates a high-entropy password containing every character class, using crypto randomness. */
export function generateStrongPassword(length = 24): string {
  const all = Object.values(PASSWORD_CHARSETS).join("");
  const pick = (chars: string) => chars[crypto.randomInt(chars.length)];
  const required = Object.values(PASSWORD_CHARSETS).map(pick);
  const rest = Array.from({ length: Math.max(length - required.length, 0) }, () => pick(all));
  const combined = [...required, ...rest];
  for (let i = combined.length - 1; i > 0; i -= 1) {
    const j = crypto.randomInt(i + 1);
    [combined[i], combined[j]] = [combined[j], combined[i]];
  }
  return combined.join("");
}

export class BootstrapError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "BootstrapError";
  }
}

export interface CreatePlatformAdminInput {
  email: string;
  fullName: string;
  password?: string;
  resetPassword?: boolean;
}

export interface CreatePlatformAdminResult {
  status: "CREATED" | "EXISTING" | "PASSWORD_RESET";
  userId: string;
  tenantId: string;
  email: string;
  /** Only present when a password was generated by this call. */
  generatedPassword?: string;
}

export async function createPlatformAdmin(
  input: CreatePlatformAdminInput
): Promise<CreatePlatformAdminResult> {
  const email = input.email.trim().toLowerCase();
  const fullName = input.fullName.trim();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    throw new BootstrapError("A valid administrator email address is required.");
  }
  if (fullName.length < 2) {
    throw new BootstrapError("Administrator full name must be at least 2 characters.");
  }
  if (input.password !== undefined && input.password.length < MIN_ADMIN_PASSWORD_LENGTH) {
    throw new BootstrapError(
      `Administrator passwords must be at least ${MIN_ADMIN_PASSWORD_LENGTH} characters.`
    );
  }

  const client = await pool.connect();
  try {
    await client.query("BEGIN;");

    let tenantId = (
      await client.query("SELECT id FROM tenants WHERE slug = $1 AND type = 'TLI' LIMIT 1;", [
        PLATFORM_TENANT_SLUG,
      ])
    ).rows[0]?.id as string | undefined;
    if (!tenantId) {
      tenantId = crypto.randomUUID();
      await client.query(
        `INSERT INTO tenants (id, type, name, slug, industry, is_sdf, status)
         VALUES ($1, 'TLI', $2, $3, 'Compliance Platform', FALSE, 'ACTIVE');`,
        [tenantId, PLATFORM_TENANT_NAME, PLATFORM_TENANT_SLUG]
      );
      await client.query(
        `INSERT INTO audit_logs (tenant_id, action, entity_type, entity_id, new_state)
         VALUES ($1, 'PLATFORM_TENANT_CREATED', 'tenants', $1, $2);`,
        [tenantId, JSON.stringify({ slug: PLATFORM_TENANT_SLUG })]
      );
    }

    const existing = (
      await client.query("SELECT id, tenant_id, role FROM users WHERE LOWER(email) = $1 LIMIT 1;", [
        email,
      ])
    ).rows[0];

    if (existing && (existing.role !== "TLI_SUPER_ADMIN" || existing.tenant_id !== tenantId)) {
      throw new BootstrapError(
        "This email already belongs to a non-administrator account. Use a different email."
      );
    }

    if (existing && !input.resetPassword) {
      await client.query("COMMIT;");
      return { status: "EXISTING", userId: existing.id, tenantId, email };
    }

    const generatedPassword = input.password ? undefined : generateStrongPassword();
    const passwordHash = await hashPassword(input.password ?? generatedPassword!);

    let userId: string;
    if (existing) {
      userId = existing.id;
      await client.query(
        `UPDATE users
         SET password_hash = $1, is_active = TRUE, session_version = session_version + 1,
             updated_at = CURRENT_TIMESTAMP
         WHERE id = $2;`,
        [passwordHash, userId]
      );
    } else {
      userId = crypto.randomUUID();
      await client.query(
        `INSERT INTO users (id, tenant_id, email, password_hash, full_name, role, is_active, email_verified_at)
         VALUES ($1, $2, $3, $4, $5, 'TLI_SUPER_ADMIN', TRUE, CURRENT_TIMESTAMP);`,
        [userId, tenantId, email, passwordHash, fullName]
      );
    }
    await client.query(
      `INSERT INTO audit_logs (tenant_id, user_id, action, entity_type, entity_id, new_state)
       VALUES ($1, $2, $3, 'users', $2, $4);`,
      [
        tenantId,
        userId,
        existing ? "PLATFORM_ADMIN_PASSWORD_RESET" : "PLATFORM_ADMIN_CREATED",
        JSON.stringify({ email, role: "TLI_SUPER_ADMIN" }),
      ]
    );

    await client.query("COMMIT;");
    return {
      status: existing ? "PASSWORD_RESET" : "CREATED",
      userId,
      tenantId,
      email,
      generatedPassword,
    };
  } catch (err) {
    await client.query("ROLLBACK;");
    throw err;
  } finally {
    client.release();
  }
}
